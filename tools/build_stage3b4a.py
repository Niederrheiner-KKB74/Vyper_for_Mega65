def thin_font():
    result={}
    for c,rows in THIN_FONT.items():
        code=ord(c)-64 if "A"<=c<="Z" else ord(c)
        result[code]=bytes([int(row,2)<<2 for row in rows.split("/")]+[0])
    return result

def templates():
    screen, colours = bytearray(), bytearray()
    def char(c): return ord(c)-64 if 'A'<=c<='Z' else ord(c)
    for row in range(25):
        words=[480]; attributes=[0x6010]
        if row in (2,6,12,17):
            words += [129]*10
            attributes += [0x0b00]*10
        else:
            label,colour=LABELS.get(row,('',0x0a))
            words += [128|0x8000]+[char(c) for c in label.center(9)]+[128|0x8000]
            attributes += [0x0b00]+[colour<<8]*9+[0x0b00]
        while len(words)<20:
            words.append(640); attributes.append(0x6010)
        words.append(0); attributes.append(0x0010)
        assert len(words)==len(attributes)==21
        screen += b''.join(w.to_bytes(2,'little') for w in words)
        colours += b''.join(w.to_bytes(2,'little') for w in attributes)
    required={ord(c)-64 if "A"<=c<="Z" else ord(c) for text,_ in LABELS.values() for c in text}
    assert required <= thin_font().keys(), "HUD glyph missing"
    return bytes(screen),bytes(colours)

